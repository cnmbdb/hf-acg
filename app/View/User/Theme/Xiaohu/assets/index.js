    const langKey = "xiaohu_lang";
    let currentLang = localStorage.getItem(langKey) || "zh-CN";

    function t(key) {
        return (i18n[currentLang] && i18n[currentLang][key]) || i18n["zh-CN"][key] || key;
    }

    function applyI18n() {
        document.documentElement.setAttribute("lang", currentLang);
        document.documentElement.setAttribute("data-xh-lang", currentLang);
        $("[data-i18n]").each(function () {
            $(this).text(t($(this).data("i18n")));
        });
        $("[data-i18n-placeholder]").each(function () {
            $(this).attr("placeholder", t($(this).data("i18n-placeholder")));
        });
        $("[data-i18n-aria-label]").each(function () {
            $(this).attr("aria-label", t($(this).data("i18n-aria-label")));
        });
        $("[data-lang-option]").removeClass("is-active").filter(`[data-lang-option="${currentLang}"]`).addClass("is-active");
    }

    window.XiaohuI18n = {
        t,
        lang: () => currentLang,
        set(lang) {
            if (!i18n[lang]) return;
            currentLang = lang;
            localStorage.setItem(langKey, lang);
            applyI18n();
            $(document).trigger("xiaohu:i18n");
        },
        apply: applyI18n
    };

    function normalizeAmount(value) {
        const num = Number(value);
        if (!Number.isFinite(num)) return value;
        return String(num).replace(/(\.\d*?)0+$/, "$1").replace(/\.$/, "");
    }

    function protectItemBasePrice() {
        const priceEl = document.querySelector(".xh-item-price .price[data-base-price]");
        if (!priceEl) return;
        const base = Number(priceEl.getAttribute("data-base-price"));
        if (!Number.isFinite(base) || base <= 0) return;

        function applyBaseWhenZero() {
            const text = (priceEl.textContent || "").replace(/[^\d.]/g, "");
            const current = Number(text || 0);
            if (current === 0) {
                priceEl.innerHTML = `<span class="unit">¥</span>${normalizeAmount(base)}`;
            }
        }

        applyBaseWhenZero();
        new MutationObserver(applyBaseWhenZero).observe(priceEl, {
            childList: true,
            subtree: true,
            characterData: true
        });
    }

